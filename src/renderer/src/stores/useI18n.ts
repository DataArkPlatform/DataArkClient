export type I18nKey = keyof typeof zh

/** v1 固定中文；结构保留 en 字典，后续可扩展 */
type Lang = 'zh' | 'en'

const dicts: Record<Lang, Record<I18nKey, string>> = {
  zh,
  en: { ...en, ...(enExtras as Partial<Record<I18nKey, string>>) } as Record<I18nKey, string>
}

/** 带 {placeholder} 的格式化翻译 */
function format(template: string, params: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (m, k: string) =>
    k in params ? String(params[k]) : m
  )
}

interface I18nState {
  language: Lang
  t: (key: I18nKey) => string
  /** 带参数版本：字典值形如 '已导出 {n} 个文件' */
  tFmt: (key: I18nKey, params: Record<string, string | number>) => string
}

export const useI18n = create<I18nState>(() => ({
  language: 'zh',
  t: (key) => dicts.zh[key],
  tFmt: (key, params) => format(dicts.zh[key], params)
}))
